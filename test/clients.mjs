import { chromium } from 'playwright';
const ok = (n, c) => { console.log((c ? 'PASS ' : 'FAIL ') + n); if (!c) process.exitCode = 1; };
const B = 'http://localhost:8787'; const PW = 'test-pass-123456';
const br = await chromium.launch();
for (const [label, vp] of [['desktop', { width: 1100, height: 900 }], ['phone', { width: 390, height: 844 }]]) {
  const ctx = await br.newContext({ viewport: vp }); const pg = await ctx.newPage(); const errs = []; pg.on('pageerror', e => errs.push(String(e)));
  await pg.goto(B + '/app/login.html'); await pg.fill('#id', 'tabish'); await pg.fill('#pw', PW); await pg.click('#go'); await pg.waitForURL('**/app/');
  await pg.waitForTimeout(700);
  await pg.evaluate(() => { location.hash = '#clients'; }); await pg.waitForTimeout(1200);
  ok(label + ': Clients opens live', /New client/.test(await pg.textContent('#main')));
  const N = 'Test Client ' + label + Date.now();
  await pg.click('[data-act=clnew][data-id="1"]');
  await pg.click('[data-act=clcreate]'); await pg.waitForTimeout(700);
  ok(label + ': empty name refused', /Not saved/.test(await pg.innerText('body')));
  await pg.fill('#cn_name', N); await pg.click('[data-act=clcreate]'); await pg.waitForTimeout(1500);
  ok(label + ': client created and opened', (await pg.textContent('#main')).includes(N) && /Plan and terms/.test(await pg.textContent('#main')));
  let t = await pg.textContent('#main');
  ok(label + ': starts with ball on us', /Your move/.test(t) && /No contact logged yet/.test(t));
  await pg.click('[data-act=cltouch]'); await pg.waitForTimeout(1200);
  t = await pg.textContent('#main');
  ok(label + ': touch flips ball to them', /Waiting on them/.test(t) && /Spoke today/.test(t));
  ok(label + ': 7-day strip shows today', (await pg.locator('.cl-week i.on').count()) === 1);
  await pg.click('[data-act=clball][data-v=us]'); await pg.waitForTimeout(1000);
  ok(label + ': ball switch back to us', /Your move/.test(await pg.textContent('#main')));
  await pg.check('[data-act=clchk][data-i="0"]'); await pg.waitForTimeout(1000);
  ok(label + ': checklist saved', await pg.isChecked('[data-act=clchk][data-i="0"]'));
  await pg.click('[data-act=clstage]'); await pg.waitForTimeout(1200);
  ok(label + ': moved to pilot', /Pilot/.test(await pg.textContent('.cl-rail span.on')));
  await pg.fill('#cd_next_step', 'Send terms PDF'); await pg.click('[data-act=clsave]'); await pg.waitForTimeout(1500);
  t = await pg.textContent('#main');
  ok(label + ': saved next step', (await pg.inputValue('#cd_next_step')) === 'Send terms PDF');
  ok(label + ': no money on the page', !/EUR|USD|Payments|Price/.test(await pg.textContent('#main')));
  await pg.fill('#ct_title', 'Collect logo'); await pg.click('[data-act=cltask]'); await pg.waitForTimeout(1500);
  ok(label + ': client task shown', (await pg.textContent('#main')).includes('Collect logo'));
  ok(label + ': history lists the changes', /Pilot/.test(await pg.textContent('#main')));
  await pg.screenshot({ path: '/tmp/clients-' + label + '.png', fullPage: true });
  const noscroll = await pg.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1);
  ok(label + ': no sideways scroll', noscroll);
  await pg.click('[data-act=clopen][data-id=""]'); await pg.waitForTimeout(500);
  ok(label + ': listed on overview', (await pg.textContent('#main')).includes(N));
  const blocked = await pg.evaluate(async () => (await fetch('/app/api/clients', { method: 'POST', headers: { 'content-type': 'application/json' }, body: '{"name":"x"}' })).status);
  ok(label + ': write without x-uns header refused', blocked >= 400);
  ok(label + ': no page errors', errs.length === 0); if (errs.length) console.log(errs);
  await ctx.close();
}
await br.close();
