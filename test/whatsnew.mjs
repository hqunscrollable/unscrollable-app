import { chromium } from 'playwright';
const ok = (n, c) => { console.log((c ? 'PASS ' : 'FAIL ') + n); if (!c) process.exitCode = 1; };
const B = 'http://localhost:8787', H = { 'x-uns': '1', 'content-type': 'application/json' };
const PW = 'test-pass-123456';
const adm = (await fetch(B + '/app/api/login', { method: 'POST', headers: H, body: JSON.stringify({ login_id: 'tabish', password: PW }) })).headers.getSetCookie()[0].split(';')[0];
const b = await chromium.launch(); const pg = await b.newPage({ viewport: { width: 1100, height: 900 } }); const errs = []; pg.on('pageerror', e => errs.push(String(e)));
const nu = await (await fetch(B + '/app/api/admin/users', { method: 'POST', headers: { ...H, cookie: adm }, body: JSON.stringify({ name: 'WN', login_id: 'wn' + (Date.now() % 100000), role: 'founder' }) })).json();
const lid = nu.path ? null : null;
await fetch(B + '/app/api/reset', { method: 'POST', headers: H, body: JSON.stringify({ token: nu.path.split('#')[1], password: PW }) });
const login = (await (await fetch(B + '/app/api/admin/users', { headers: { cookie: adm } })).json()).users.filter(u => u.name === 'WN').pop().login_id;
await pg.goto(B + '/app/login.html'); await pg.fill('#id', login); await pg.fill('#pw', PW); await pg.click('#go'); await pg.waitForURL('**/app/');
await pg.waitForSelector('[data-act=nav]'); await pg.waitForTimeout(500);
ok('banner shows on Today', /New in 1\.3\.7/.test(await pg.textContent('#main')));
await pg.screenshot({ path: '/tmp/wn_banner.png' });
await pg.click('[data-act=relseen]'); await pg.waitForTimeout(400);
ok('Got it hides banner', !/New in 1\.3\.7/.test(await pg.textContent('#main')));
await pg.reload(); await pg.waitForSelector('[data-act=nav]'); await pg.waitForTimeout(500);
ok('stays hidden after reload (saved on server)', !/New in 1\.3\.7/.test(await pg.textContent('#main')));
await pg.click('[data-act=nav][data-id=whatsnew]'); await pg.waitForTimeout(300);
const t = await pg.textContent('#main');
ok('page lists all releases with three parts', /How it cuts friction/.test(t) && /1\.2\.2/.test(t) && /1\.3\.0/.test(t));
await pg.screenshot({ path: '/tmp/wn_page.png' });
ok('no page errors', errs.length === 0); await b.close();
