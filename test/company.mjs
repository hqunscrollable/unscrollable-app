import { chromium } from 'playwright';
const ok = (n, c) => { console.log((c ? 'PASS ' : 'FAIL ') + n); if (!c) process.exitCode = 1; };
const B = 'http://localhost:8787'; const PW = 'test-pass-123456';
const br = await chromium.launch(); const ctx = await br.newContext({ viewport: { width: 390, height: 900 }, deviceScaleFactor: 2 });
await ctx.grantPermissions(['clipboard-read','clipboard-write']);
const pg = await ctx.newPage(); const errs = []; pg.on('pageerror', e => errs.push(String(e)));
await pg.goto(B + '/app/login.html'); await pg.fill('#id', 'tabish'); await pg.fill('#pw', PW); await pg.click('#go'); await pg.waitForURL('**/app/');
await pg.waitForSelector('#nav [data-id=leads]', { state: 'attached' });
await pg.evaluate(() => { location.hash = '#leads'; }); await pg.waitForTimeout(800);
const chips = await pg.$$('.co'); ok('company chips show on the leads board', chips.length >= 20);
const tenor = await pg.$$eval('.co', els => els.filter(e => /Tenor/.test(e.textContent)).map(e => e.textContent.trim()));
ok('Tenor shows a count of 3', tenor.length >= 1 && tenor.every(t => /3/.test(t)));
const hues = await pg.$$eval('.co', els => els.filter(e => /Tenor/.test(e.textContent)).map(e => e.style.getPropertyValue('--h')));
ok('same company, same colour', new Set(hues).size === 1);
await pg.screenshot({ path: '/tmp/co-board.png' });
const cb = await pg.$('.item:has(.co:has-text("Chromie")) [data-act=lcopy]'); ok('copy link button on a lead with a link', !!cb);
await cb.click(); await pg.waitForTimeout(200);
ok('button says Copied', /Copied/.test(await cb.textContent()));
ok('link is on the clipboard', (await pg.evaluate(() => navigator.clipboard.readText())) === 'https://www.linkedin.com/in/ananth-s/');
ok('no copy button when there is no link', (await pg.$$('.item:has(.co:has-text("Toven")) [data-act=lcopy]')).length === 0);
ok('X and Copy X buttons show for Ananth', (await pg.$$('.item:has(.co:has-text("Chromie")) a[href="https://x.com/_ananthhh"]')).length === 1 && (await pg.$$('.item:has(.co:has-text("Chromie")) [data-act=lcopy][data-url="https://x.com/_ananthhh"]')).length === 1);
ok('no X button where YC has no X (Toven)', (await pg.$$('.item:has(.co:has-text("Toven")) a[href*="x.com"]')).length === 0);
await pg.evaluate(() => localStorage.setItem('uns-theme', 'dark')); await pg.reload(); await pg.waitForSelector('#nav [data-id=leads]', { state: 'attached' });
ok('saved theme choice is used after reload', (await pg.getAttribute('html', 'data-theme')) === 'dark');
await pg.click('.item:has(.co:has-text("Tenor")) [data-act=lopen]'); await pg.waitForTimeout(400);
await pg.evaluate(() => {}); 
const opened = await pg.$('.drawer'); ok('lead card opens', !!opened);
const txt = opened ? await opened.innerText() : '';
ok('card lists the other two Tenor founders', /Same company: Tenor/.test(txt) && /Amgad|Hamze|Muhtasham/.test(txt));
await pg.screenshot({ path: '/tmp/co-drawer.png' });
ok('no page errors', errs.length === 0); if (errs.length) console.log(errs);
await br.close();
