import { chromium } from 'playwright';
import { totpNow } from '../src/crypto.js';
const B = 'http://localhost:8799/app/api', H = { 'x-uns': '1', 'content-type': 'application/json' };
const ok = (n, c, x) => { console.log((c ? 'PASS ' : 'FAIL ') + n + (c ? '' : ' ' + x)); if (!c) process.exitCode = 1; };
const post = (p, b, ck) => fetch(B + p, { method: 'POST', headers: { ...H, ...(ck ? { cookie: ck } : {}) }, body: JSON.stringify(b || {}) });
const PW = 'test-pass-123456';
const adm = (await post('/login', { login_id: 'tabish', password: PW })).headers.getSetCookie()[0].split(';')[0];
const lid = 'ru' + (Date.now() % 1000000);
const nu = await (await post('/admin/users', { name: 'RC UI', login_id: lid, role: 'founder' }, adm)).json();
await post('/reset', { token: nu.path.split('#')[1], password: PW });
const ck = (await post('/login', { login_id: lid, password: PW })).headers.getSetCookie()[0].split(';')[0];
const su = await (await post('/2fa/setup', {}, ck)).json(); await post('/2fa/enable', { code: await totpNow(su.secret) }, ck);
const b = await chromium.launch(); const pg = await b.newPage({ viewport: { width: 1100, height: 800 } }); const errs = []; pg.on('pageerror', e => errs.push(String(e)));
await pg.goto('http://localhost:8799/app/login.html'); await pg.fill('#id', lid); await pg.fill('#pw', PW); await pg.fill('#code', await totpNow(su.secret)); await pg.check('#rem'); await pg.click('#go'); await pg.waitForURL('**/app/');
await pg.waitForSelector('[data-act=nav]'); await pg.click('[data-act=nav][data-id=account]'); await pg.waitForTimeout(300);
ok('recovery card shows 10 left', /10 unused codes left/.test(await pg.textContent('#main')));
await pg.fill('#rc_pw', PW); await pg.click('[data-act=rcnew]'); await pg.waitForTimeout(500);
ok('codes shown', await pg.locator('.rcodes span').count() === 10);
await pg.screenshot({ path: '/tmp/codes.png', fullPage: true });
await pg.click('[data-act=rcsave]'); await pg.waitForTimeout(200);
ok('codes hidden after saved', await pg.locator('.rcodes').count() === 0);
await pg.click('[data-act=devforget]'); await pg.waitForTimeout(300);
ok('no page errors', errs.length === 0, errs.join('|')); await b.close();
