import { chromium } from 'playwright';
const ok = (n, c) => { console.log((c ? 'PASS ' : 'FAIL ') + n); if (!c) process.exitCode = 1; };
const B = 'http://localhost:8787'; const PW = 'test-pass-123456';
const br = await chromium.launch(); const pg = await (await br.newContext({ viewport: { width: 1200, height: 900 } })).newPage(); const errs = []; pg.on('pageerror', e => errs.push(String(e)));
await pg.goto(B + '/app/login.html'); await pg.fill('#id', 'tabish'); await pg.fill('#pw', PW); await pg.click('#go'); await pg.waitForURL('**/app/');
await pg.waitForSelector('#nav .grp'); await pg.waitForTimeout(400);
const items = () => pg.$$eval('#nav [data-act=nav]', els => els.map(e => e.getAttribute('data-id')));
const groups = await pg.$$eval('#nav .grp', els => els.map(e => e.textContent.trim() + ':' + e.getAttribute('aria-expanded')));
console.log(groups.join(' | '));
ok('all-demo groups start folded', groups.some(g => /Agreements.*false/.test(g)));
ok('Today stays visible', (await items()).includes('home'));
const before = (await items()).length;
await pg.click('#nav .grp:has-text("Agreements")'); await pg.waitForTimeout(200);
ok('unfold shows its items', (await items()).includes('ndas'));
await pg.reload(); await pg.waitForSelector('#nav .grp'); await pg.waitForTimeout(400);
ok('choice remembered after reload', (await items()).includes('ndas'));
await pg.click('#nav .grp:has-text("Agreements")'); await pg.waitForTimeout(200);
ok('fold hides them again', !(await items()).includes('ndas'));
await pg.click('#nav .grp:has-text("Daily")'); await pg.waitForTimeout(200);
ok('a live group can be folded too', !(await items()).includes('leads') );
ok('no page errors', errs.length === 0); if (errs.length) console.log(errs);
await br.close();
