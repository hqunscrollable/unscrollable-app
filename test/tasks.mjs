await p.goto('http://localhost:8799/app/'); await p.fill('#id', 'tabish'); await p.fill('#pw', 'test-pass-123456'); await p.click('#go');
await p.waitForSelector('[data-act="nav"][data-id="tasks"]'); await p.click('[data-act="nav"][data-id="tasks"]');
await p.fill('#tk_q', 'Port tasks screen'); await p.press('#tk_q', 'Enter'); await p.waitForTimeout(700);
